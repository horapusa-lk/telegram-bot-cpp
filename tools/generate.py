        items: list[tuple[int, str, str]] = []
        for t in self.structs + self.markers:
            items.append((len(t.get("fields", [])) + 3, "struct", t["name"]))
        alias_names = (["ChatId", "ReplyMarkup"] + [u["name"] for u in self.unions]
                       + sorted(NAMED_ADHOC_UNIONS.values()))
        for a in alias_names:
            items.append((6, "union", a))
        shards: list[list[tuple[str, str]]] = [[] for _ in range(NUM_JSON_SHARDS)]
        weights = [0] * NUM_JSON_SHARDS
        for weight, kind, name in sorted(items, reverse=True):
            i = weights.index(min(weights))
            weights[i] += weight
            shards[i].append((kind, name))

        files: list[str] = []
        for shard in shards:
            out: list[str] = [BANNER]
            out.append('#include "tgbot/api_error.hpp"\n#include "tgbot/types.hpp"\n\n')
            struct_part = [n for k, n in shard if k == "struct"]
            union_part = [n for k, n in shard if k == "union"]
