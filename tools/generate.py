#!/usr/bin/env python3
"""Generate the C++ type system, JSON glue, registry and round-trip tests from
spec/api_inventory.json.

Emits (all files carry a do-not-edit banner):
  include/tgbot/types.hpp        every API object type
  include/tgbot/version.hpp      api_version()
  src/generated/types_json_*.cpp to_json/from_json definitions (sharded)
  src/generated/registry.cpp     implemented-symbol registry (coverage gate)
  tests/unit/generated/roundtrip_corpus_*.cpp  synthetic round-trip samples

Run from anywhere: paths are anchored to the repo root.
"""

from __future__ import annotations

import json
import re
import textwrap
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INV = ROOT / "spec" / "api_inventory.json"

BANNER = "// Generated by tools/generate.py from spec/api_inventory.json — do not edit.\n"

SCALAR_CPP = {
    "integer": "std::int64_t",
    "string": "std::string",
    "boolean": "bool",
    "true": "bool",
    "float": "double",
}

# Unions that cannot be dispatched by a discriminator literal.
STRUCTURAL_UNIONS = {"MaybeInaccessibleMessage", "InputMessageContent"}

# InputMessageContent subtypes in dispatch order (Venue before Location: both
# carry latitude, only Venue has title).
INPUT_MESSAGE_CONTENT_ORDER = [
    ("InputTextMessageContent", "message_text"),
    ("InputRichMessageContent", "rich_message"),
    ("InputContactMessageContent", "phone_number"),
    ("InputInvoiceMessageContent", "payload"),
    ("InputVenueMessageContent", "title"),
    ("InputLocationMessageContent", "latitude"),
]

# Ad-hoc aliases for inline unions that appear in the reference without a name.
REPLY_MARKUP_SET = frozenset(
    ["InlineKeyboardMarkup", "ReplyKeyboardMarkup", "ReplyKeyboardRemove", "ForceReply"]
)
NAMED_ADHOC_UNIONS = {
    # InputRichMessageMedia.media: not a subset of InputMedia (VoiceNote is
    # rich-message-only), so it gets its own alias.
    frozenset(
        [
            "InputMediaAnimation",
            "InputMediaAudio",
            "InputMediaPhoto",
            "InputMediaVideo",
            "InputMediaVoiceNote",
        ]
    ): "InputRichMessageMediaContent",
}

# Synthetic sample value overrides (field-exact), used by the round-trip corpus.
SAMPLE_OVERRIDES = {
    ("InaccessibleMessage", "date"): 0,  # docs: always 0, and the union dispatch key
}

NUM_JSON_SHARDS = 6
NUM_TEST_SHARDS = 4


def esc_doc(text: str) -> str:
    """Escape scraped description text for safe Doxygen output."""
    text = text.replace("\\", "&#92;")
    text = text.replace("@", "\\@")
    text = text.replace("<", "\\<").replace(">", "\\>")
    text = text.replace("&", "\\&")
    text = text.replace("#", "\\#")
    return text


def wrap_comment(text: str, indent: str) -> str:
    lines: list[str] = []
    for para in text.split("\n"):
        wrapped = textwrap.wrap(para, width=96 - len(indent)) or [""]
        lines.extend(wrapped)
    body = "\n".join(f"{indent}/// {line}".rstrip() for line in lines)
    if any(ord(c) > 127 for c in text):
        # clang-format miscounts display width of emoji and never settles on
        # these lines; guard them so format checks stay stable.
        body = f"{indent}// clang-format off\n{body}\n{indent}// clang-format on"
    return body


def paraphrase(desc: str) -> str:
    """Mechanical paraphrase of scraped descriptions for doc comments."""
    subs = [
        (r"^This object represents ", "Represents "),
        (r"^This object describes ", "Describes "),
        (r"^This object contains ", "Contains "),
        (r"^This object defines ", "Defines "),
        (r"^Describes that ", "Indicates that "),
        (r"^Use this method to ", "Uses the Bot API to "),
    ]
    for pat, rep in subs:
        desc = re.sub(pat, rep, desc)
    return desc


class Generator:
    def __init__(self) -> None:
        inv = json.loads(INV.read_text(encoding="utf-8"))
        self.version: str = inv["bot_api_version"]
        self.types: list[dict] = inv["types"]
        self.methods: list[dict] = inv["methods"]
        self.by_name = {t["name"]: t for t in self.types}
        self.structs = [t for t in self.types if t["kind"] == "struct"]
        self.unions = [t for t in self.types if t["kind"] == "union"]
        self.markers = [t for t in self.types if t["kind"] == "marker"]
        self.union_names = {t["name"] for t in self.unions}
        self.union_of = {t["name"]: t["subtypes"] for t in self.unions}
        self._promote_attach_strings()
        self.discriminators: dict[str, tuple[str, dict[str, str]]] = {}
        self._find_discriminators()
        self.emitted: list[Path] = []
        self.scc_of: dict[str, int] = {}
        self.order: list[str] = []
        self._analyze_graph()
        self.terminating: set[str] = set()
        self._compute_terminating()
        self.union_order: dict[str, list[str]] = {}
        self._compute_union_order()

    def _promote_attach_strings(self) -> None:
        """Fields documented as String but accepting attach:// upload
        references (nested media, thumbnails, covers, sticker payloads) become
        tgbot::InputFile so users can upload through them directly.  The
        passthrough forms serialize verbatim, so round-trips are unaffected."""
        count = 0
        for entry in self.structs + self.methods:
            for f in entry.get("fields", entry.get("params", [])):
                if f["type"] == {"kind": "string"} and "attach://" in f["description"]:
                    f["type"] = {"kind": "ref", "name": "InputFile"}
                    count += 1
        self.attach_promotions = count

    # ---------------------------------------------------------------- unions
    def literal_of_struct(self, sname: str) -> tuple[str, str] | None:
        """(discriminator field, literal) declared by a struct, if any.

        "must be one of ..." describes an enumeration, not a single constant,
        so it must not match (it would bake the literal "one" into fields
        like InputSticker.format)."""
        for f in self.by_name[sname].get("fields", []):
            if f["type_raw"] == "String" and f["required"]:
                m = re.search(r'always ["“]([A-Za-z0-9_]+)["”]', f["description"]) or re.search(
                    r"must be (?!one of\b)([a-z0-9_]+)", f["description"]
                )
                if m:
                    return (f["name"], m.group(1))
        return None

    def _find_discriminators(self) -> None:
        """For each discriminated union: (field, {subtype: literal})."""
        for u in self.unions:
            name = u["name"]
            if name in STRUCTURAL_UNIONS:
                continue
            self.discriminators[name] = self._discriminate(name, u["subtypes"])
        for members, alias in NAMED_ADHOC_UNIONS.items():
            self.discriminators[alias] = self._discriminate(alias, sorted(members))

    def _discriminate(self, name: str, subtypes: list[str]) -> tuple[str, dict[str, str]]:
        field_names = set()
        literals: dict[str, str] = {}
        for sub in subtypes:
            found = self.literal_of_struct(sub)
            if not found:
                raise SystemExit(f"union {name}: no discriminator literal in {sub}")
            field_names.add(found[0])
            literals[sub] = found[1]
        if len(field_names) != 1:
            raise SystemExit(f"union {name}: mixed discriminator fields {field_names}")
        return (next(iter(field_names)), literals)

    def _collision_key(self, union: str, candidates: list[str]) -> dict[str, str | None]:
        """For subtypes sharing a literal, a required field unique to each (the
        last candidate falls through to else and may be None)."""
        result: dict[str, str | None] = {}
        for sub in candidates:
            mine = [f["name"] for f in self.by_name[sub].get("fields", []) if f["required"]]
            others: set[str] = set()
            for o in candidates:
                if o != sub:
                    others |= {f["name"] for f in self.by_name[o].get("fields", [])}
            unique = [n for n in mine if n not in others]
            result[sub] = unique[0] if unique else None
        missing = [s for s, k in result.items() if k is None]
        if len(missing) > 1:
            raise SystemExit(f"union {union}: cannot disambiguate {missing}")
        return result

    # ----------------------------------------------------------- type graph
    def _value_deps(self, ast: dict, *, top: bool = True) -> set[str]:
        """Types whose *definition* must precede a field of this AST type.
        Array elements never require completeness (vector allows incomplete)."""
        kind = ast["kind"]
        if kind == "array":
            return set()
        if kind == "ref":
            name = ast["name"]
            if name == "InputFile":
                return set()
            if name in self.union_of:
                deps = set()
                for sub in self.union_of[name]:
                    deps.add(sub)
                return deps
            return {name}
        if kind == "union":
            opts = ast["options"]
            names = self._union_ref_names(opts)
            if names is None:
                return set()  # ChatId / InputFile-or-String: no struct deps
            deps: set[str] = set()
            for n in names:
                deps |= self._value_deps({"kind": "ref", "name": n})
            return deps
        return set()

    def _union_ref_names(self, opts: list[dict]) -> list[str] | None:
        if all(o["kind"] == "ref" for o in opts):
            names = [o["name"] for o in opts]
            if "InputFile" in names:
                return None
            return names
        return None

    def _analyze_graph(self) -> None:
        graph: dict[str, set[str]] = defaultdict(set)
        nodes = [t["name"] for t in self.structs] + [t["name"] for t in self.markers]
        node_set = set(nodes)
        for t in self.structs:
            for f in t.get("fields", []):
                for dep in self._value_deps(f["type"]):
                    if dep in node_set:
                        graph[t["name"]].add(dep)
        # Tarjan SCC (iterative).
        index: dict[str, int] = {}
        low: dict[str, int] = {}
        on_stack: set[str] = set()
        stack: list[str] = []
        counter = [0]
        scc_id = [0]

        def strongconnect(root: str) -> None:
            work = [(root, iter(sorted(graph[root])))]
            index[root] = low[root] = counter[0]
            counter[0] += 1
            stack.append(root)
            on_stack.add(root)
            while work:
                v, it = work[-1]
                advanced = False
                for w in it:
                    if w not in index:
                        index[w] = low[w] = counter[0]
                        counter[0] += 1
                        stack.append(w)
                        on_stack.add(w)
                        work.append((w, iter(sorted(graph[w]))))
                        advanced = True
                        break
                    if w in on_stack:
                        low[v] = min(low[v], index[w])
                if advanced:
                    continue
                work.pop()
                if low[v] == index[v]:
                    while True:
                        w = stack.pop()
                        on_stack.discard(w)
                        self.scc_of[w] = scc_id[0]
                        if w == v:
                            break
                    scc_id[0] += 1
                if work:
                    parent = work[-1][0]
                    low[parent] = min(low[parent], low[v])

        for n in nodes:
            if n not in index:
                strongconnect(n)

        # Topological order of the DAG that remains once boxed edges (same-SCC)
        # are dropped.  Kahn over reversed edges: deps first.
        dag: dict[str, set[str]] = {n: set() for n in nodes}
        for a, deps in graph.items():
            for b in deps:
                if self.scc_of[a] != self.scc_of[b]:
                    dag[a].add(b)
                elif a != b:
                    # A genuine same-SCC pair: both get boxed, no edge either way.
                    pass
        indeg = {n: 0 for n in nodes}
        rdeps: dict[str, set[str]] = defaultdict(set)
        for a, deps in dag.items():
            indeg[a] = len(deps)
            for b in deps:
                rdeps[b].add(a)
        ready = sorted(n for n, d in indeg.items() if d == 0)
        order: list[str] = []
        while ready:
            n = ready.pop(0)
            order.append(n)
            for a in sorted(rdeps[n]):
                indeg[a] -= 1
                if indeg[a] == 0:
                    ready.append(a)
            ready.sort()
        if len(order) != len(nodes):
            raise SystemExit("type graph is not a DAG after boxing")
        self.order = order

    def _eager_closure(self) -> dict[str, set[str]]:
        """Transitive closure of "default construction eagerly constructs".

        Required struct-value and Box fields construct their type; required
        union-value fields conservatively construct every subtype (the actual
        first alternative is what this analysis is choosing).  Vectors and
        optionals construct nothing.
        """
        eager: dict[str, set[str]] = defaultdict(set)
        for t in self.structs:
            for f in t.get("fields", []):
                if not f["required"]:
                    continue
                ast = f["type"]
                names: list[str] = []
                if ast["kind"] == "ref" and ast["name"] != "InputFile":
                    n = ast["name"]
                    names = self.union_of.get(n, [n])
                elif ast["kind"] == "union":
                    refs = self._union_ref_names(ast["options"])
                    if refs:
                        names = refs
                for n in names:
                    if n in self.by_name and self.by_name[n]["kind"] in ("struct", "marker"):
                        eager[t["name"]].add(n)
        closure: dict[str, set[str]] = {}

        def dfs(n: str) -> set[str]:
            if n in closure:
                return closure[n]
            closure[n] = set()  # cycle-tolerant: cycles resolve to partial sets
            acc: set[str] = set()
            for d in eager.get(n, ()):
                acc.add(d)
                acc |= dfs(d)
            closure[n] = acc
            return acc

        for t in self.structs:
            dfs(t["name"])
        return closure

    def _compute_union_order(self) -> None:
        """Variant alternative order: doc order, except the first alternative
        must be default-construction-safe (defaulting the variant must never
        re-enter the union through a required Box field, e.g. RichTextBold's
        required Box<RichText> text)."""
        closure = self._eager_closure()
        all_sets = {u["name"]: u["subtypes"] for u in self.unions}
        for members, alias in NAMED_ADHOC_UNIONS.items():
            all_sets[alias] = sorted(members)
        for name, subs in all_sets.items():
            member_set = set(subs)
            safe = [s for s in subs if not (closure.get(s, set()) & member_set)]
            if not safe:
                raise SystemExit(f"union {name}: no default-safe first alternative")
            first = safe[0]
            self.union_order[name] = [first] + [s for s in subs if s != first]

    def field_is_boxed(self, owner: str, ast: dict) -> bool:
        deps = self._value_deps(ast)
        return any(self.scc_of.get(d) == self.scc_of.get(owner) for d in deps if d != "")

    # ------------------------------------------------------------ C++ types
    def cpp_base_type(self, ast: dict, owner: str) -> str:
        kind = ast["kind"]
        if kind in SCALAR_CPP:
            return SCALAR_CPP[kind]
        if kind == "array":
            return f"std::vector<{self.cpp_base_type(ast['item'], owner)}>"
        if kind == "ref":
            return ast["name"]
        if kind == "union":
            opts = ast["options"]
            kinds = sorted(o["kind"] for o in opts)
            if kinds == ["integer", "string"]:
                return "ChatId"
            names = [o["name"] for o in opts if o["kind"] == "ref"]
            if "InputFile" in names:
                return "InputFile"  # "InputFile or String"
            if frozenset(names) == REPLY_MARKUP_SET:
                return "ReplyMarkup"
            # Inline subset of a named union: use the smallest named superset
            # (e.g. sendMediaGroup's media list fits both InputMedia and the
            # larger InputPollMedia; InputMedia is the right home).
            supersets = [u for u in self.unions if set(names) <= set(u["subtypes"])]
            if supersets:
                best = min(supersets, key=lambda u: (len(u["subtypes"]), u["name"]))
                return best["name"]
            if frozenset(names) in NAMED_ADHOC_UNIONS:
                return NAMED_ADHOC_UNIONS[frozenset(names)]
            raise SystemExit(f"{owner}: unmapped inline union {names}")
        raise SystemExit(f"{owner}: unknown AST kind {kind}")

    def cpp_field_type(self, owner: str, field: dict) -> str:
        base = self.cpp_base_type(field["type"], owner)
        if self.field_is_boxed(owner, field["type"]):
            base = f"Box<{base}>"
        if not field["required"]:
            base = f"std::optional<{base}>"
        return base

    # -------------------------------------------------------------- headers
    def emit_types_hpp(self) -> str:
        out: list[str] = []
        w = out.append
        w(BANNER)
        w("#pragma once\n\n")
        w("/// @file\n/// @brief Every Telegram Bot API object type "
          f"(Bot API {self.version}).\n\n")
        w("#include <cstdint>\n#include <optional>\n#include <string>\n"
          "#include <variant>\n#include <vector>\n\n")
        w("#include <nlohmann/json.hpp>\n\n")
        w('#include "tgbot/box.hpp"\n#include "tgbot/detail/json.hpp"\n'
          '#include "tgbot/input_file.hpp"\n\n')
        w("namespace tgbot {\n\n")

        # Forward declarations.
        w("// -- forward declarations "
          "---------------------------------------------------\n")
        for name in sorted(t["name"] for t in self.structs + self.markers):
            w(f"struct {name};\n")
        w("\n")

        # Aliases: ChatId, ReplyMarkup, and every documented union.
        w("// -- union aliases "
          "-----------------------------------------------------------\n\n")
        w("/// Chat identifier: a numeric id or a @c \\@channelusername string.\n")
        w("using ChatId = std::variant<std::int64_t, std::string>;\n\n")
        w("/// Any of the four keyboard-control markups accepted by send methods.\n")
        w("using ReplyMarkup = std::variant<InlineKeyboardMarkup, ReplyKeyboardMarkup,\n"
          "                                 ReplyKeyboardRemove, ForceReply>;\n\n")
        for u in self.unions:
            doc = wrap_comment(esc_doc(paraphrase(u["description"])), "")
            w(doc + "\n")
            w(f"/// @see https://core.telegram.org/bots/api#{u['anchor']}\n")
            alts = ", ".join(self.union_order[u["name"]])
            w(f"using {u['name']} = std::variant<{alts}>;\n\n")
        for members, alias in sorted(NAMED_ADHOC_UNIONS.items(), key=lambda kv: kv[1]):
            w(f"/// Media accepted where the reference lists an unnamed union of\n"
              f"/// input-media types.\n")
            alts = ", ".join(self.union_order[alias])
            w(f"using {alias} = std::variant<{alts}>;\n\n")

        w("}  // namespace tgbot\n\n")

        # adl_serializer declarations (variants live in namespace std, so ADL
        # cannot find free functions; full specializations are required).
        w("// -- serializer declarations for the variant aliases "
          "------------------------\n")
        w("namespace nlohmann {\n")
        alias_names = (["ChatId", "ReplyMarkup"] + [u["name"] for u in self.unions]
                       + sorted(NAMED_ADHOC_UNIONS.values()))
        seen_sig: set[str] = set()
        for name in alias_names:
            sig = self.alias_signature(name)
            if sig in seen_sig:
                raise SystemExit(f"duplicate variant signature for {name}")
            seen_sig.add(sig)
            w(f"template <>\nstruct adl_serializer<tgbot::{name}> {{\n")
            w(f"    static void to_json(json& j, const tgbot::{name}& value);\n")
            w(f"    static void from_json(const json& j, tgbot::{name}& value);\n")
            w("};\n")
        w("}  // namespace nlohmann\n\n")

        w("namespace tgbot {\n\n")
        w("// -- object types "
          "------------------------------------------------------------\n\n")
        marker_names = {t["name"] for t in self.markers}
        for name in self.order:
            t = self.by_name[name]
            doc = wrap_comment(esc_doc(paraphrase(t["description"])), "")
            w(doc + "\n")
            w(f"/// @see https://core.telegram.org/bots/api#{t['anchor']}\n")
            if name in marker_names:
                w(f"struct {name} {{}};\n\n")
            else:
                lit = self.literal_of_struct(name)
                w(f"struct {name} {{\n")
                for f in t.get("fields", []):
                    fdoc = wrap_comment(esc_doc(f["description"]), "    ")
                    w(fdoc + "\n")
                    cpp = self.cpp_field_type(name, f)
                    if lit and f["name"] == lit[0] and f["required"] and cpp == "std::string":
                        init = f' = "{lit[1]}"'  # discriminator pre-filled
                    elif f["type"]["kind"] == "true" and f["required"]:
                        init = "{true}"  # documented as always True
                    elif cpp in ("bool", "double", "std::int64_t"):
                        init = "{}"
                    else:
                        # No NSDMI here: object types may hold vectors of
                        # yet-incomplete elements (recursive rich content),
                        # and a {} initializer would instantiate their
                        # constructors mid-definition.
                        init = ""
                    w(f"    {cpp} {f['name']}{init};\n")
                w("};\n\n")
            w(f"/// Serializes {name} into its Bot API wire format.\n")
            w(f"void to_json(nlohmann::json& j, const {name}& value);\n")
            w(f"/// Parses {name} from its Bot API wire format.\n")
            w(f"void from_json(const nlohmann::json& j, {name}& value);\n\n")
        w("}  // namespace tgbot\n")
        return "".join(out)

    def alias_signature(self, name: str) -> str:
        if name == "ChatId":
            return "int64,string"
        if name == "ReplyMarkup":
            return ",".join(sorted(REPLY_MARKUP_SET))
        return ",".join(sorted(self.union_members(name)))

    def union_members(self, name: str) -> list[str]:
        if name in self.union_of:
            return self.union_of[name]
        for members, alias in NAMED_ADHOC_UNIONS.items():
            if alias == name:
                return sorted(members)
        raise KeyError(name)

    # ------------------------------------------------------------- json cpp
    def emit_struct_json(self, t: dict) -> str:
        name = t["name"]
        out: list[str] = []
        w = out.append
        fields = t.get("fields", [])
        if not fields:
            w(f"void to_json(nlohmann::json& j, const {name}& /*value*/) {{\n"
              "    j = nlohmann::json::object();\n}\n")
            w(f"void from_json(const nlohmann::json& /*j*/, {name}& /*value*/) {{}}\n\n")
            return "".join(out)
        w(f"void to_json(nlohmann::json& j, const {name}& value) {{\n")
        w("    j = nlohmann::json::object();\n")
        for f in fields:
            w(f'    detail::write(j, "{f["name"]}", value.{f["name"]});\n')
        w("}\n")
        w(f"void from_json(const nlohmann::json& j, {name}& value) {{\n")
        for f in fields:
            w(f'    detail::read(j, "{f["name"]}", value.{f["name"]});\n')
        w("}\n\n")
        return "".join(out)

    def emit_union_json(self, name: str) -> str:
        out: list[str] = []
        w = out.append
        qn = f"tgbot::{name}"
        w(f"void adl_serializer<{qn}>::to_json(json& j, const {qn}& value) {{\n")
        w("    std::visit([&j](const auto& alt) { j = alt; }, value);\n}\n")
        w(f"void adl_serializer<{qn}>::from_json(const json& j, {qn}& value) {{\n")
        if name == "ChatId":
            w("    if (j.is_string()) {\n        value = j.get<std::string>();\n")
            w("    } else {\n        value = j.get<std::int64_t>();\n    }\n}\n\n")
            return "".join(out)
        if name == "ReplyMarkup":
            pairs = [
                ("inline_keyboard", "InlineKeyboardMarkup"),
                ("keyboard", "ReplyKeyboardMarkup"),
                ("remove_keyboard", "ReplyKeyboardRemove"),
                ("force_reply", "ForceReply"),
            ]
            for i, (key, sub) in enumerate(pairs):
                kw = "if" if i == 0 else "} else if"
                w(f'    {kw} (j.contains("{key}")) {{\n        value = j.get<tgbot::{sub}>();\n')
            w('    } else {\n        throw tgbot::Error("unrecognized ReplyMarkup object");\n    }\n}\n\n')
            return "".join(out)
        if name == "MaybeInaccessibleMessage":
            w('    if (j.at("date").get<std::int64_t>() == 0) {\n')
            w("        value = j.get<tgbot::InaccessibleMessage>();\n")
            w("    } else {\n        value = j.get<tgbot::Message>();\n    }\n}\n\n")
            return "".join(out)
        if name == "InputMessageContent":
            for i, (sub, key) in enumerate(INPUT_MESSAGE_CONTENT_ORDER):
                kw = "if" if i == 0 else "} else if"
                w(f'    {kw} (j.contains("{key}")) {{\n        value = j.get<tgbot::{sub}>();\n')
            w('    } else {\n        throw tgbot::Error("unrecognized InputMessageContent object");\n    }\n}\n\n')
            return "".join(out)

        field, literals = self.discriminators[name]
        by_literal: dict[str, list[str]] = defaultdict(list)
        for sub in self.union_members(name):
            by_literal[literals[sub]].append(sub)
        w(f'    const auto& d = j.at("{field}").get_ref<const std::string&>();\n')
        first = True
        for literal in sorted(by_literal):
            subs = by_literal[literal]
            kw = "if" if first else "} else if"
            first = False
            w(f'    {kw} (d == "{literal}") {{\n')
            if len(subs) == 1:
                w(f"        value = j.get<tgbot::{subs[0]}>();\n")
            else:
                keys = self._collision_key(name, subs)
                ordered = [s for s in subs if keys[s] is not None]
                fallback = [s for s in subs if keys[s] is None]
                inner_first = True
                for s in ordered[: len(ordered) if fallback else -1]:
                    ikw = "if" if inner_first else "} else if"
                    inner_first = False
                    w(f'        {ikw} (j.contains("{keys[s]}")) {{\n')
                    w(f"            value = j.get<tgbot::{s}>();\n")
                last = fallback[0] if fallback else ordered[-1]
                w(f"        }} else {{\n            value = j.get<tgbot::{last}>();\n        }}\n")
        w("    } else {\n")
        w(f'        throw tgbot::Error("unknown {name} {field}: " + d);\n    }}\n}}\n\n')
        return "".join(out)

