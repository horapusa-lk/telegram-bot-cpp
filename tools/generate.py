    # ------------------------------------------------------ round-trip data
    def _compute_terminating(self) -> None:
        """Fixpoint: a struct terminates when every *required* field can be
        sampled finitely (unions terminate when any subtype does; arrays
        always terminate because [] is valid)."""
        for t in self.markers:
            self.terminating.add(t["name"])
        self.terminating.add("InputFile")

        def ast_term(ast: dict) -> bool:
            kind = ast["kind"]
            if kind in SCALAR_CPP or kind == "array":
                return True
            if kind == "ref":
                n = ast["name"]
                if n in self.union_of:
                    return any(s in self.terminating for s in self.union_of[n])
                return n in self.terminating
            if kind == "union":
                names = self._union_ref_names(ast["options"])
                if names is None:
                    return True  # ChatId / InputFile-or-String
                return any(n in self.terminating for n in names)
            return True

        changed = True
        while changed:
            changed = False
            for t in self.structs:
                if t["name"] in self.terminating:
                    continue
                if all(ast_term(f["type"]) for f in t.get("fields", []) if f["required"]):
                    self.terminating.add(t["name"])
                    changed = True
        missing = [t["name"] for t in self.structs if t["name"] not in self.terminating]
        if missing:
            raise SystemExit(f"non-terminating required cycles: {missing}")

    def pick_subtype(self, names: list[str], stack: tuple[str, ...]) -> str:
        """First union subtype that can be sampled finitely, avoiding the
        current expansion stack when possible."""
        fresh = [n for n in names if n in self.terminating and n not in stack]
        if fresh:
            return fresh[0]
        terminating = [n for n in names if n in self.terminating]
        if terminating:
            return terminating[0]
        raise SystemExit(f"no terminating subtype among {names}")

    def sample(self, name: str, depth: int, stack: tuple[str, ...]):
        t = self.by_name[name]
        if t["kind"] == "special":  # InputFile
            return "file-ref"
        if t["kind"] == "marker":
            return {}
        if t["kind"] == "union":
            return self.sample(self.pick_subtype(t["subtypes"], stack), depth, stack)
        obj = {}
        disc = None
        for u, (field, literals) in self.discriminators.items():
            if name in literals:
                disc = (field, literals[name])
                break
        for f in t.get("fields", []):
            if not f["required"] and (depth >= 2 or self._recurses(f["type"], stack)):
                continue
            if (name, f["name"]) in SAMPLE_OVERRIDES:
                obj[f["name"]] = SAMPLE_OVERRIDES[(name, f["name"])]
                continue
            if disc and f["name"] == disc[0]:
                obj[f["name"]] = disc[1]
                continue
            obj[f["name"]] = self.sample_of_ast(f["type"], depth + 1, stack + (name,))
        return obj

    def _recurses(self, ast: dict, stack: tuple[str, ...]) -> bool:
        kind = ast["kind"]
        if kind == "ref":
            n = ast["name"]
            if n in stack:
                return True
            if n in self.union_of:
                return any(s in stack for s in self.union_of[n])
            return False
        if kind == "array":
            return self._recurses(ast["item"], stack)
        if kind == "union":
            return any(o["kind"] == "ref" and self._recurses(o, stack) for o in ast["options"])
        return False

    def sample_of_ast(self, ast: dict, depth: int, stack: tuple[str, ...]):
        kind = ast["kind"]
        if kind == "integer":
            return 7
        if kind == "string":
            return "s"
        if kind in ("boolean", "true"):
            return True
        if kind == "float":
            return 1.5
        if kind == "array":
            if self._recurses(ast["item"], stack) or depth > 6:
                return []
            return [self.sample_of_ast(ast["item"], depth + 1, stack)]
        if kind == "ref":
            name = ast["name"]
            if name in self.union_of:
                return self.sample(self.pick_subtype(self.union_of[name], stack), depth, stack)
            return self.sample(name, depth, stack)
        if kind == "union":
            kinds = sorted(o["kind"] for o in ast["options"])
            if kinds == ["integer", "string"]:
                return 7
            names = [o["name"] for o in ast["options"] if o["kind"] == "ref"]
            if "InputFile" in names:
                return "file-ref"
            return self.sample(self.pick_subtype(names, stack), depth, stack)
        raise SystemExit(f"sample: unknown kind {kind}")

    def emit_roundtrip_shards(self) -> list[str]:
        cases: list[tuple[str, str, object]] = []  # (label, cpp expr type, sample)
        for t in self.structs + self.markers:
            cases.append((t["name"], t["name"], self.sample(t["name"], 0, ())))
        for u in self.unions:
            for sub in u["subtypes"]:
                cases.append((f"{u['name']}/{sub}", u["name"], self.sample(sub, 0, ())))
        shards: list[list[tuple[str, str, object]]] = [[] for _ in range(NUM_TEST_SHARDS)]
        for i, c in enumerate(cases):
            shards[i % NUM_TEST_SHARDS].append(c)
        files = []
        for si, shard in enumerate(shards):
            out: list[str] = [BANNER]
            w = out.append
            w('#include "roundtrip.hpp"\n\n')
            w("// NOLINTBEGIN\n")
            w(f"const std::vector<tgbot::test::RoundtripCase>& tgbot::test::corpus_{si}() {{\n")
            w("    static const std::vector<RoundtripCase> cases = {\n")
            for label, cpp, sample in shard:
                sample_json = json.dumps(sample, separators=(",", ":")).replace("\\", "\\\\").replace('"', '\\"')
                w("        {\n")
                w(f'            "{label}",\n')
                w(f'            "{sample_json}",\n')
                w(f"            [](const nlohmann::json& j) {{ return nlohmann::json(j.get<tgbot::{cpp}>()); }},\n")
                w("        },\n")
            w("    };\n    return cases;\n}\n")
            w("// NOLINTEND\n")
            files.append("".join(out))
        return files

    # -------------------------------------------------------- method layer
    def _compute_file_bearing(self) -> set[str]:
        """Types that can transitively carry an InputFile upload."""

        def mentions(ast: dict, bearing: set[str]) -> bool:
            kind = ast["kind"]
            if kind == "ref":
                n = ast["name"]
                if n == "InputFile":
                    return True
                if n in self.union_of:
                    return any(s in bearing for s in self.union_of[n])
                return n in bearing
            if kind == "array":
                return mentions(ast["item"], bearing)
            if kind == "union":
                names = self._union_ref_names(ast["options"]) or []
                if any(o["kind"] == "ref" and o["name"] == "InputFile" for o in ast["options"]):
                    return True
                return any(mentions({"kind": "ref", "name": n}, bearing) for n in names)
            return False

        bearing: set[str] = set()
        changed = True
        while changed:
            changed = False
            for t in self.structs:
                if t["name"] in bearing:
                    continue
                if any(mentions(f["type"], bearing) for f in t.get("fields", [])):
                    bearing.add(t["name"])
                    changed = True
        return bearing

    @staticmethod
    def pascal(method: str) -> str:
        return method[0].upper() + method[1:]

    def params_struct_name(self, m: dict) -> str | None:
        return f"{self.pascal(m['name'])}Params" if m["params"] else None

    def return_cpp(self, ast: dict) -> str:
        kind = ast["kind"]
        if kind == "true":
            return "bool"
        if kind in SCALAR_CPP:
            return SCALAR_CPP[kind]
        if kind == "ref":
            return ast["name"]
        if kind == "array":
            return f"std::vector<{self.return_cpp(ast['item'])}>"
        if kind == "union":
            opts = {json.dumps(o, sort_keys=True) for o in ast["options"]}
            expected = {
                json.dumps({"kind": "ref", "name": "Message"}, sort_keys=True),
                json.dumps({"kind": "true"}, sort_keys=True),
            }
            if opts == expected:
                return "MessageOrBool"
            raise SystemExit(f"unhandled union return: {ast}")
        raise SystemExit(f"unhandled return kind: {kind}")

    def return_parse_expr(self, ast: dict) -> str:
        cpp = self.return_cpp(ast)
        if cpp == "MessageOrBool":
            return "detail::parse_message_or_bool(std::move(result))"
        return f"result.get<{cpp}>()"

    def method_doc(self, m: dict, indent: str = "") -> str:
        doc = wrap_comment(esc_doc(paraphrase(m["description"])), indent)
        doc += f"\n{indent}///\n"
        if m["params"]:
            doc += f"{indent}/// @param params see {self.params_struct_name(m)}.\n"
        doc += (f"{indent}/// @throws ApiError on a Bot API error, NetworkError when "
                f"transport fails.\n")
        doc += f"{indent}/// @see https://core.telegram.org/bots/api#{m['anchor']}\n"
        return doc

    def emit_api_hpp(self, file_bearing: set[str]) -> str:
        out: list[str] = []
        w = out.append
        w(BANNER)
        w("#pragma once\n\n")
        w(f"/// @file\n/// @brief tgbot::Api — every Bot API {self.version} method.\n\n")
        w("#include <chrono>\n#include <cstdint>\n#include <optional>\n"
          "#include <string>\n#include <utility>\n#include <variant>\n#include <vector>\n\n")
        w('#include "tgbot/api_client.hpp"\n#include "tgbot/detail/collect.hpp"\n'
          '#include "tgbot/types.hpp"\n\n')
        w("namespace tgbot {\n\n")
        w("/// Result of the editMessage* family: the edited Message for normal\n"
          "/// messages, or @c true when the target was an inline message.\n")
        w("using MessageOrBool = std::variant<Message, bool>;\n\n")
        w("namespace detail {\n\n")
        w("/// Parses a result that is either a Message object or literal true.\n")
        w("inline MessageOrBool parse_message_or_bool(nlohmann::json&& result) {\n")
        w("    if (result.is_boolean()) {\n        return result.get<bool>();\n    }\n")
        w("    return result.get<Message>();\n}\n\n")
        w("}  // namespace detail\n\n")

        # Params structs.
        for m in self.methods:
            if not m["params"]:
                continue
            sname = self.params_struct_name(m)
            w(f"/// Parameters of Api::{m['name']}(); fields mirror the official\n")
            w(f"/// documentation order, so designated initializers read like the docs.\n")
            w(f"/// @see https://core.telegram.org/bots/api#{m['anchor']}\n")
