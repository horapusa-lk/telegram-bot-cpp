    def _ast_carries_file(self, ast: dict, file_bearing: set[str]) -> bool:
        kind = ast["kind"]
        if kind == "ref":
            n = ast["name"]
            if n == "InputFile":
                return True
            if n in self.union_of:
                return any(s in file_bearing for s in self.union_of[n])
            return n in file_bearing
        if kind == "array":
            return self._ast_carries_file(ast["item"], file_bearing)
        if kind == "union":
            if any(o["kind"] == "ref" and o["name"] == "InputFile" for o in ast["options"]):
                return True
            names = self._union_ref_names(ast["options"]) or []
            return any(self._ast_carries_file({"kind": "ref", "name": n}, file_bearing)
                       for n in names)
        return False

    def emit_api_shards(self, file_bearing: set[str], count: int = 4) -> list[str]:
        shards: list[list[dict]] = [[] for _ in range(count)]
        weights = [0] * count
        for m in sorted(self.methods, key=lambda m: -len(m["params"])):
            i = weights.index(min(weights))
            weights[i] += len(m["params"]) + 3
            shards[i].append(m)
        files = []
        for shard in shards:
            out: list[str] = [BANNER]
            w = out.append
            w('#include "tgbot/api.hpp"\n'
              '#include "tgbot/detail/collect_generated.hpp"\n\n')
            w("namespace tgbot {\n\n")
            for m in sorted(shard, key=lambda m: m["name"]):
                ret = self.return_cpp(m["return"])
                sname = self.params_struct_name(m)
                if sname is None:
                    w(f"{ret} Api::{m['name']}() const {{\n")
                    w(f'    auto result = client_.call("{m["name"]}", '
                      "nlohmann::json::object());\n")
                else:
                    w(f"{ret} Api::{m['name']}(const {sname}& params) const {{\n")
                    w("    nlohmann::json body = nlohmann::json::object();\n")
                    for p in m["params"]:
                        w(f'    detail::write(body, "{p["name"]}", params.{p["name"]});\n')
                    file_params = [p for p in m["params"]
                                   if self._ast_carries_file(p["type"], file_bearing)]
                    if file_params:
                        w("    std::vector<MultipartPart> files;\n")
                        for p in file_params:
                            w(f"    collect_files(params.{p['name']}, files);\n")
                    files_arg = "std::move(files)" if file_params else "{}"
                    if m["name"] == "getUpdates":
                        # Long polling: transport timeout must exceed the poll.
                        w("    std::chrono::milliseconds timeout{};\n")
                        w("    if (params.timeout.has_value()) {\n")
                        w("        timeout = std::chrono::seconds(*params.timeout + 10);\n")
                        w("    }\n")
                        w(f'    auto result = client_.call("{m["name"]}", std::move(body), '
                          f"{files_arg}, timeout);\n")
                    else:
                        w(f'    auto result = client_.call("{m["name"]}", std::move(body), '
                          f"{files_arg});\n")
                w(f"    return {self.return_parse_expr(m['return'])};\n}}\n\n")
            w("}  // namespace tgbot\n")
            files.append("".join(out))
        return files

